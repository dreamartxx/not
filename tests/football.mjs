const {matchSignal,filterMatches}=await import('../assets/football.js');
const now=Date.parse('2026-10-17T16:00:00Z');
const scheduled={id:'1',date:'2026-10-17T16:30:00Z',time_confirmed:true,state:'pre',status:'STATUS_SCHEDULED',home_id:'83',away_id:'86',competition:'uefa.champions'};
assert.equal(matchSignal(scheduled,now).kind,'soon');
assert.equal(matchSignal({...scheduled,time_confirmed:false},now).kind,'scheduled');
assert.equal(matchSignal({...scheduled,date:'2026-10-17T15:00Z'},now).kind,'pending');
assert.equal(matchSignal({...scheduled,state:'in',clock:"12'",live_checked_at:new Date(now-30000).toISOString()},now).kind,'live');
assert.equal(matchSignal({...scheduled,state:'in',live_checked_at:new Date(now-181000).toISOString()},now).kind,'pending');
assert.equal(matchSignal({...scheduled,status:'STATUS_POSTPONED'},now).kind,'paused');
assert.equal(matchSignal({...scheduled,state:'post'},now).kind,'finished');
const old={...scheduled,id:'2',date:'2026-09-10T15:00Z',state:'post'};
assert.deepEqual(filterMatches([scheduled,old],{period:'past',now}).map(m=>m.id),['2']);
assert.equal(filterMatches([scheduled,old],{period:'all',from:'2026-10-01',to:'2026-10-31',competition:'champions',now}).length,1);
assert.equal(filterMatches([scheduled],{team:'465',now}).length,0);
console.log('PASS: upcoming light, confirmed live freshness, postponed/final states and archive/date/team/competition filters.');
